"""행정구역 표준화.

분석 단위는 '시·군·자치구'(일반구, 출장소 제외)이며 2025년 말 행정구역을 기준으로 한다.
- 주민등록(행정코드): 11 서울, 26 부산, ... 41 경기, 51 강원, 52 전북, 46 전남 ...
  2026년부터 광주·전남이 '12 전남광주통합특별시'로 표시되므로 이름으로 되돌려 매핑한다.
- e-지방지표(통계용 코드): 11 서울, 21 부산, 22 대구, 23 인천, 24 광주, 25 대전, 26 울산,
  29 세종, 31 경기, 32 강원, 33 충북, 34 충남, 35 전북, 36 전남, 37 경북, 38 경남, 39 제주.
  2026년 자료는 광주·전남이 1224/1236 접두로 표기된다.
"""
